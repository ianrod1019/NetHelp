// ── Region matching ──

const REGION_ALIASES = [
  { keys: ['tulsa'], region: 'Tulsa, OK' },
  { keys: ['oklahoma city', 'okc'], region: 'Oklahoma City, OK' },
  { keys: ['norman'], region: 'Norman, OK' },
  { keys: ['broken arrow'], region: 'Broken Arrow, OK' },
]

export const supportedRegions = Object.keys(regionData)

export function resolveRegion(regionStr) {
  if (!regionStr) return null
  const lower = regionStr.toLowerCase()
  for (const { keys, region } of REGION_ALIASES) {
    if (keys.some((k) => lower.includes(k))) return region
  }
  return null
}

export function getRegionData(regionStr) {
  const key = resolveRegion(regionStr)
  if (!key) return null
  return regionData[key]
}

export function getEvents(regionStr) {
  return getRegionData(regionStr)?.events ?? []
}

export function getInternships(regionStr) {
  return getRegionData(regionStr)?.internships ?? []
}

export function getGedCenters(regionStr) {
  return getRegionData(regionStr)?.gedCenters ?? []
}

export function getMentors(regionStr) {
  return getRegionData(regionStr)?.mentors ?? []
}

// Flatten across all regions — for lookups by ID (e.g. EventDetail, Profile RSVP list)
export function getAllEvents() {
  return Object.values(regionData).flatMap((r) => r.events)
}

export function getAllMentors() {
  return Object.values(regionData).flatMap((r) => r.mentors)
}

